// Package task2slices — задача 2: «срез не хранит элементы».
//
// В переменной типа []int лежит заголовок из трёх полей: указатель на массив,
// длина и вместимость. Сами элементы лежат в массиве, и на один массив может
// смотреть сколько угодно срезов. Отсюда два эффекта, которые ниже надо
// научиться контролировать: чужая правка видна через ваш срез, а append при
// свободной вместимости пишет в чужой хвост.
//
// Запуск: go test ./task2slices
package task2slices

// Head возвращает первые n элементов src отдельным срезом.
//
// Отдельным — значит, что запись в результат не должна менять src, а запись
// в src не должна менять результат. Для n вне диапазона 0..len(src) функция
// паникует так же, как обычное выражение среза.
func Head(src []int, n int) []int {
	// TODO(задача 2): срез от среза не копирует элементы — он смотрит
	// в тот же массив.
	s := src[:n]
	res := make([]int, n)
	copy(res, s)
	return res
}

// AddTag возвращает срез из tags с добавленным в конец tag.
//
// Исходный tags и любой другой срез, смотрящий в тот же массив, изменяться
// не должны — в том числе за пределами len(tags), где у массива может быть
// занятый хвост.
func AddTag(tags []string, tag string) []string {
	// TODO(задача 2): если у tags есть свободная вместимость, append пишет
	// новый элемент прямо в общий массив — поверх того, что там уже лежит.
	res := make([]string, len(tags)+1)
	copy(res, tags)
	res[len(tags)] = tag
	return res
}

// SharesArray сообщает, начинаются ли a и b в одном и том же месте одного
// и того же массива.
//
// Это дешёвый способ увидеть общую память своими глазами, а не поверить на
// слово. Граница метода честная: срез, взятый из середины чужого массива
// (например src[2:]), начинается в другом месте, и SharesArray вернёт false,
// хотя массив у них общий. Для пустых срезов результат — false: у них нет
// элемента, адрес которого можно взять.
func SharesArray(a, b []int) bool {
	// TODO(задача 2): длины тут ни при чём. Сравнивать нужно адреса первых
	// элементов: &a[0] и &b[0].
	if len(a) == 0 || len(b) == 0 {
		return false
	}
	// Сравниваем адреса первых элементов базовых массивов
	return &a[0] == &b[0]
}
