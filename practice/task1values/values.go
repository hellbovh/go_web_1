// Package task1values — задача 1: «копия или оригинал».
//
// В переменной типа Counter лежит сама структура: два поля подряд. Когда такую
// переменную присваивают, передают в функцию или достают из цикла range, копируются
// оба поля. Обе функции ниже написаны так, как их обычно пишут в первый раз, —
// и обе меняют копию. Тесты это показывают; ваша задача — сделать так, чтобы
// изменения видел тот, кто вызвал функцию.
//
// Запуск: go test ./task1values
package task1values

// Counter — счётчик обращений к одному эндпоинту за день.
type Counter struct {
	Name string
	Hits int
}

// Hit увеличивает Hits у счётчика, на который указывает p.
//
// После вызова Hit(&c) значение c.Hits обязано вырасти на единицу.
func Hit(p *Counter) {
	// TODO(задача 1): сейчас в c лежит копия структуры, а не она сама.
	// Разыменование даёт значение; чтобы изменить оригинал, писать нужно
	// по указателю.
	p.Hits++
}

// HitAll увеличивает Hits у каждого счётчика в day.
//
// После вызова HitAll(day) у каждого элемента day значение Hits обязано вырасти
// на единицу.
func HitAll(day []Counter) {
	// TODO(задача 1): range со вторым значением кладёт в c копию элемента.
	// Оригинал живёт в day[i].
	for i := range day {
		day[i].Hits++
	}
}

// Busiest возвращает имя счётчика с наибольшим Hits.
//
// Эта функция уже написана и в задачу не входит: она нужна тестам как
// независимый способ посмотреть на day после ваших правок. При равенстве
// побеждает тот, кто встретился раньше; для пустого day возвращается "".
func Busiest(day []Counter) string {
	best := ""
	top := -1
	for i := range day {
		if day[i].Hits > top {
			best, top = day[i].Name, day[i].Hits
		}
	}
	return best
}
