// Package task3zero — задача 3: «что лежит в переменной до первого присваивания».
//
// В Go нет неинициализированных переменных: у каждого типа есть нулевое значение,
// и оно уже лежит в переменной. Для int это 0, для string — "", для среза и карты —
// nil. Но nil-срез и nil-карта ведут себя по-разному, и именно на этой разнице
// ломается первый рабочий код: в nil-срез можно добавлять через append, а запись
// в nil-карту — это паника во время выполнения.
//
// Запуск: go test ./task3zero
package task3zero

// Profile — профиль пользователя: имя, метки и произвольные метаданные.
type Profile struct {
	Name string
	Tags []string
	Meta map[string]string
}

// NewProfile возвращает профиль с именем name, в Meta которого можно писать сразу
// после создания.
//
// Tags при этом оставляем как есть: nil-срез — рабочее значение, append на нём
// работает, и заводить пустой срез заранее незачем.
func NewProfile(name string) Profile {
	// TODO(задача 3): у возвращённого профиля Meta остаётся nil, и первая же
	// запись в него паникует. Карту нужно создать.
	return Profile{
		Name: name,
		Meta: make(map[string]string),
	}
}

// SetMeta записывает value по ключу key в метаданные профиля.
//
// Функция обязана работать и тогда, когда профиль создан не через NewProfile
// и Meta в нём ещё nil: например var p Profile.
func SetMeta(p *Profile, key, value string) {
	// TODO(задача 3): запись в nil-карту — это panic: assignment to entry in
	// nil map. Проверьте карту перед записью.
	if p.Meta == nil {
		p.Meta = make(map[string]string)
	}
	p.Meta[key] = value
}

// Lookup возвращает значение по ключу и признак того, что ключ вообще есть
// в метаданных.
//
// Различать здесь нужно два разных случая: ключа нет вовсе и ключ есть, но
// в нём лежит пустая строка. Чтение из nil-карты паниковать не должно —
// оно и не паникует.
func Lookup(p Profile, key string) (string, bool) {
	// TODO(задача 3): чтение из карты умеет возвращать два значения, и второе —
	// это как раз «ключ есть». Пустая строка сама по себе про наличие ключа
	// ничего не говорит.
	value, key_exist := p.Meta[key]
	return value, key_exist
}
