// Command demo печатает наблюдения, на которых держится теория вебинара
// «Что лежит в переменной».
//
//	go run ./cmd/demo
//
// Программа ничего не проверяет и не требует решённых задач: её можно запускать
// в любой момент, в том числе до первой правки. Каждая строка — результат
// операции, выполненной прямо сейчас, а не заранее записанный текст.
package main

import (
	"fmt"

	"gobasics/variables/internal/demo"
)

func main() {
	for _, line := range demo.Run().Lines() {
		fmt.Println(line)
	}
}
